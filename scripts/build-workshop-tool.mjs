import fs from 'node:fs/promises'
import path from 'node:path'
import crypto from 'node:crypto'
import { spawn } from 'node:child_process'
import AdmZip from 'adm-zip'

// Pinned upstream + two small integration patches. No changes to Steam download logic.
const sourceUrl =
  'https://github.com/SteamRE/DepotDownloader/archive/refs/tags/DepotDownloader_3.4.0.zip'
const sourceHash = '3bd1259ce6a26bcf0e61450e48ffd8bd5e455eae904cc4e2340a6d7773e7a5d0'
const root = path.resolve('.scratch/steam-account-tool')
const sha = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex')
await fs.mkdir(root, { recursive: true })
const archive = path.join(root, 'source.zip')
let bytes = await fs.readFile(archive).catch(() => null)
if (!bytes || sha(bytes) !== sourceHash) {
  const response = await fetch(sourceUrl)
  if (!response.ok) throw new Error('Unable to fetch pinned DepotDownloader source')
  bytes = Buffer.from(await response.arrayBuffer())
  if (sha(bytes) !== sourceHash) throw new Error('DepotDownloader source hash mismatch')
  await fs.writeFile(archive, bytes)
}
const sourceZip = new AdmZip(bytes)
if (
  sourceZip
    .getEntries()
    .some(
      (entry) => entry.entryName.split(/[\\/]/).includes('..') || /^[\\/]/.test(entry.entryName)
    )
)
  throw new Error('Unsafe source archive')
sourceZip.extractAllTo(path.join(root, 'source'), true)
const project = path.join(
  root,
  'source',
  'DepotDownloader-DepotDownloader_3.4.0',
  'DepotDownloader'
)
await fs.copyFile(
  'tools/workshop/AccountSettingsStore.cs',
  path.join(project, 'AccountSettingsStore.cs')
)
const programPath = path.join(project, 'Program.cs')
let program = await fs.readFile(programPath, 'utf8')
const anchor =
  '            var appId = GetParameter(args, "-app", ContentDownloader.INVALID_APP_ID);'
if (!program.includes(anchor)) throw new Error('Upstream authentication entry changed')
program = program.replace(
  anchor,
  `            // Vertex settings can authenticate without accessing any game or downloading files.
            if (HasParameter(args, "-vertex-session-check"))
            {
                AccountSettingsStore.Save();
                Console.WriteLine("VERTEX_SESSION_V1");
                return 0;
            }
            if (HasParameter(args, "-vertex-auth-only"))
            {
                if (!InitializeSteam(username, password)) return 1;
                ContentDownloader.ShutdownSteam3();
                return 0;
            }

${anchor}`
)
await fs.writeFile(programPath, program)
const sessionPath = path.join(project, 'Steam3Session.cs')
let session = await fs.readFile(sessionPath, 'utf8')
if (!session.includes('            IsLoggedOn = true;'))
  throw new Error('Upstream login callback changed')
session = session.replace(
  '            IsLoggedOn = true;',
  '            IsLoggedOn = true;\n            Console.WriteLine("VERTEX_AUTHENTICATED");'
)
await fs.writeFile(sessionPath, session)
const output = path.join(root, 'publish')
await new Promise((resolve, reject) => {
  const child = spawn(
    'dotnet',
    [
      'publish',
      path.join(project, 'DepotDownloader.csproj'),
      '-c',
      'Release',
      '-r',
      'win-x64',
      '--self-contained',
      'true',
      '-p:PublishSingleFile=true',
      '-p:DebugType=None',
      '-o',
      output
    ],
    { stdio: 'inherit', windowsHide: true }
  )
  child.on('error', reject)
  child.on('close', (code) =>
    code === 0 ? resolve() : reject(new Error(`dotnet publish failed: ${code}`))
  )
})
const zip = new AdmZip()
zip.addLocalFile(path.join(output, 'DepotDownloader.exe'))
zip.addLocalFile(path.join(output, 'LICENSE'))
const binary = await fs.readFile(path.join(output, 'DepotDownloader.exe'))
const packed = zip.toBuffer()
await fs.writeFile('resources/workshop/DepotDownloader-windows-x64.zip', packed)
const correspondingSource = new AdmZip()
correspondingSource.addLocalFolder(path.dirname(project))
// Do not package restore/publish intermediates; the project restores its pinned dependencies.
for (const entry of correspondingSource.getEntries()) {
  if (/(^|\/)(obj|bin)\//.test(entry.entryName)) correspondingSource.deleteFile(entry)
}
correspondingSource.writeZip('resources/workshop/DepotDownloader-source.zip')
const manifest = {
  version: '3.4.0-vertex-session1',
  sourceUrl,
  sourceSha256: sourceHash,
  archiveSha256: sha(packed),
  executableSha256: sha(binary),
  protocol: 1
}
await fs.writeFile(
  'resources/workshop/tool-manifest.json',
  JSON.stringify(manifest, null, 2) + '\n'
)
await fs.writeFile(
  'src/main/services/workshop/toolManifest.js',
  '// Generated by scripts/build-workshop-tool.mjs.\nexport default ' +
    JSON.stringify(manifest, null, 2) +
    '\n'
)
console.log('Built the bundled Steam session/download tool and updated its hash manifest.')
